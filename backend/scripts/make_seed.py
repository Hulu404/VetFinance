"""Generate supabase/seed.sql from tests/golden/set01/data.json (clinics A and B).

Run from the repository root:  backend/.venv/Scripts/python backend/scripts/make_seed.py
Users test-a@vetfinance.test and test-b@vetfinance.test must exist in auth.users before the
seed is applied (memberships are linked by e-mail); otherwise memberships are simply skipped.
"""

import hashlib
import json
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "tests" / "golden" / "set01" / "data.json"
OUT = ROOT / "supabase" / "seed.sql"
NS = uuid.UUID("6f1d8e0a-4b1c-4c8e-9a53-0d2f6c1b7e11")
EMAILS = {"A": "test-a@vetfinance.test", "B": "test-b@vetfinance.test"}


def uid(kind: str, key: str) -> str:
    return str(uuid.uuid5(NS, f"{kind}:{key}"))


def q(value: object) -> str:
    if value is None:
        return "null"
    if isinstance(value, int):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def main() -> None:
    d = json.loads(DATA.read_text(encoding="utf-8"))
    lines = ["-- GENERATED by backend/scripts/make_seed.py from tests/golden/set01/data.json", ""]
    for c in d["clinics"]:
        lines.append(
            "insert into public.clinics (id, name, timezone, safe_balance) values "
            f"({q(uid('clinic', c['id']))}, {q(c['name'])}, {q(c['timezone'])}, {c['safe_balance']}) "
            "on conflict (id) do nothing;"
        )
    for a in d["accounts"]:
        lines.append(
            "insert into public.accounts (id, clinic_id, name, kind, opening_balance, opening_date) "
            f"values ({q(uid('account', a['id']))}, {q(uid('clinic', a['clinic_id']))}, {q(a['name'])}, "
            f"{q(a['type'])}, {a['opening_balance']}, {q(a['opening_date'])}) on conflict (id) do nothing;"
        )
    for t in d["transactions"]:
        digest = hashlib.sha256(
            f"{t['date']}|{t['amount']}|{t['description']}".encode()
        ).hexdigest()
        lines.append(
            "insert into public.transactions (id, clinic_id, account_id, date, description, amount, "
            "kind, source, external_id, dedup_hash, status) values "
            f"({q(uid('tx', t['id']))}, {q(uid('clinic', t['clinic_id']))}, "
            f"{q(uid('account', t['account_id']))}, {q(t['date'])}, {q(t['description'])}, {t['amount']}, "
            f"{q(t['kind'])}, {q(t['source'])}, {q(t['id'])}, {q(digest)}, {q(t['status'])}) "
            "on conflict (id) do nothing;"
        )
    for cid, email in EMAILS.items():
        lines.append(
            "insert into public.memberships (clinic_id, user_id) "
            f"select {q(uid('clinic', cid))}, u.id from auth.users u where u.email = {q(email)} "
            "on conflict (user_id, clinic_id) do nothing;"
        )
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(lines)} lines)")


if __name__ == "__main__":
    main()

"""Generate supabase/seed_set03.sql from tests/golden/set03/data.json: clinic D of golden set 3 (Рабочий стол).

Run from the repository root:  backend/.venv/Scripts/python backend/scripts/make_seed_set03.py
The user test-d@vetfinance.test must exist in auth.users before the seed is applied (the membership is
linked by e-mail); otherwise the membership is simply skipped. The seed is idempotent. Apply it only to a
test clinic. Needs the migration 20261013100000_stage2_dashboard_norms (norms are clinic settings).
"""

import json
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "tests" / "golden" / "set03" / "data.json"
OUT = ROOT / "supabase" / "seed_set03.sql"
NS = uuid.UUID("6f1d8e0a-4b1c-4c8e-9a53-0d2f6c1b7e13")
EMAIL = "test-d@vetfinance.test"
FIXED = {
    "Аренда",
    "Коммунальные и связь",
    "Налоги и взносы",
    "Зарплата",
    "Прочие расходы",
    "Реклама",
}


def uid(kind: str, key: str) -> str:
    return str(uuid.uuid5(NS, f"{kind}:{key}"))


def q(value: object) -> str:
    if value is None:
        return "null"
    if isinstance(value, int):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def category_type(name: str) -> str:
    if name.startswith("Выручка"):
        return "income"
    return "fixed" if name in FIXED else "variable"


def main() -> None:
    d = json.loads(DATA.read_text(encoding="utf-8"))
    clinic = uid("clinic", "D")
    norms = d["norms"]
    lines = [
        "-- GENERATED by backend/scripts/make_seed_set03.py from tests/golden/set03/data.json",
        "-- Clinic D (golden set 3, stage 2). Needs migration 20261013100000_stage2_dashboard_norms.",
        "",
        "insert into public.clinics (id, name, timezone, safe_balance, drugs_category, drugs_max_pct, "
        "margin_min_pct) values "
        f"({q(clinic)}, {q(d['clinic']['name'])}, {q(d['clinic']['timezone'])}, "
        f"{d['clinic']['safe_balance']}, {q(norms['drugs']['category'])}, {norms['drugs']['max_pct']}, "
        f"{norms['profit_margin']['min_pct']}) on conflict (id) do nothing;",
    ]
    for a in d["accounts"]:
        lines.append(
            "insert into public.accounts (id, clinic_id, name, kind, opening_balance, opening_date) "
            f"values ({q(uid('account', a['id']))}, {q(clinic)}, {q(a['name'])}, {q(a['type'])}, "
            f"{a['opening_balance']}, {q(a['opening_date'])}) on conflict (id) do nothing;"
        )
    names = sorted({t["category"] for t in d["transactions"] if t["category"]})
    for name in names:
        lines.append(
            "insert into public.categories (id, clinic_id, name, type) values "
            f"({q(uid('category', name))}, {q(clinic)}, {q(name)}, {q(category_type(name))}) "
            "on conflict (id) do nothing;"
        )
    for t in d["transactions"]:
        cat = uid("category", t["category"]) if t["category"] else None
        lines.append(
            "insert into public.transactions (id, clinic_id, account_id, date, description, amount, kind, "
            "source, external_id, status, category_id) values "
            f"({q(uid('tx', t['id']))}, {q(clinic)}, {q(uid('account', t['account_id']))}, {q(t['date'])}, "
            f"{q(t['description'])}, {t['amount']}, {q(t['kind'])}, {q(t['source'])}, {q(t['id'])}, "
            f"{q(t['status'])}, {q(cat)}) on conflict (id) do nothing;"
        )
    for doc in d["doctors"]:
        lines.append(
            "insert into public.doctors (id, clinic_id, external_id, code, name) values "
            f"({q(uid('doctor', doc['id']))}, {q(clinic)}, {q(doc['id'])}, {q(doc['id'])}, "
            f"{q(doc['name'])}) on conflict (id) do nothing;"
        )
    for v in d["visits"]:
        lines.append(
            "insert into public.visits (id, clinic_id, external_id, date, doctor_id) values "
            f"({q(uid('visit', v['id']))}, {q(clinic)}, {q(v['id'])}, {q(v['date'])}, "
            f"{q(uid('doctor', v['doctor_id']))}) on conflict (id) do nothing;"
        )
    for s in d["sales"]:
        payload = json.dumps(s["lines"], ensure_ascii=False)
        lines.append(
            "insert into public.sales (id, clinic_id, external_id, date, status, amount, lines) values "
            f"({q(uid('sale', s['id']))}, {q(clinic)}, {q(s['id'])}, {q(s['date'])}, {q(s['status'])}, "
            f"{s['amount']}, {q(payload)}::jsonb) on conflict (id) do nothing;"
        )
    lines.append(
        "insert into public.memberships (clinic_id, user_id) "
        f"select {q(clinic)}, u.id from auth.users u where u.email = {q(EMAIL)} "
        "on conflict (user_id, clinic_id) do nothing;"
    )
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(lines)} lines)")


if __name__ == "__main__":
    main()

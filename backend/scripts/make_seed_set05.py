"""Generate the idempotent, transactional seed of clinic F «Сосна» from golden set 5 (stage 4).

Requires all migrations through 20261017100000_stage4_planning. Apply only to a test database. The synthetic user
test-f@vetfinance.test must already exist to link the clinic to a login. Obligations are loaded as terms; their
accruals (obligation_charges) are not seeded: the application calculates them (that is what the stage 4 gate checks).
No shared data and no other clinic is modified.
"""

import json
import uuid
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "tests/golden/set05/data.json"
OUT = ROOT / "supabase/seed_set05.sql"
NS = uuid.UUID("5e0d5a3c-7c1f-4c0e-9b52-0a5f1d3e7a05")
EMAIL = "test-f@vetfinance.test"
OBLIGATION_COLUMNS = (
    "lender", "counterparty_inn", "principal", "annual_rate_bp", "payment", "payment_day",
    "first_payment_date", "payments_total", "cost", "life_years", "in_service_date",
)  # fmt: skip


def uid(kind: str, key: str) -> str:
    return str(uuid.uuid5(NS, f"{kind}:{key}"))


def q(value: object) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def generate(data: dict[str, Any]) -> str:
    clinic = uid("clinic", "F")
    lines = [
        "-- GENERATED by backend/scripts/make_seed_set05.py from tests/golden/set05/data.json",
        "-- Synthetic clinic F. Requires migration 20261017100000_stage4_planning.",
        "-- Existing rows are preserved. No obligation_charges: the application calculates them.",
        "begin;",
    ]

    def insert(table: str, conflict: str = "(id)", **values: object) -> None:
        lines.append(
            f"insert into public.{table} ({', '.join(values)}) values "
            f"({', '.join(q(v) for v in values.values())}) on conflict {conflict} do nothing;"
        )

    insert(
        "clinics",
        id=clinic,
        name=data["clinic"]["name"],
        timezone=data["clinic"]["timezone"],
        safe_balance=data["clinic"]["safe_balance"],
    )
    for a in data["accounts"]:
        insert(
            "accounts",
            id=uid("account", a["id"]),
            clinic_id=clinic,
            name=a["name"],
            kind=a["type"],
            opening_balance=a["opening_balance"],
            opening_date=a["opening_date"],
            last_statement_to=data["history"]["to"] if a["type"] == "bank" else None,
        )
    for c in data["categories"]:
        insert("categories", id=uid("category", c["name"]), clinic_id=clinic, **c)
    for t in data["transactions"]:
        insert(
            "transactions",
            id=uid("tx", t["id"]),
            clinic_id=clinic,
            account_id=uid("account", t["account_id"]),
            date=t["date"],
            description=t["description"],
            amount=t["amount"],
            kind=t["kind"],
            source=t["source"],
            external_id=t["id"],
            status=t["status"],
            category_id=uid("category", t["category"]) if t["category"] else None,
            counterparty_inn=t["counterparty_inn"],
            counterparty_name=t["counterparty_name"],
        )
    for o in data["obligations"]:
        terms = {c: o.get(c) for c in OBLIGATION_COLUMNS}
        insert(
            "obligations",
            id=uid("obligation", o["id"]),
            clinic_id=clinic,
            code=o["id"],
            name=o["name"],
            kind=o["kind"],
            **terms,
        )
    for p in data["planned_payments"]:
        insert(
            "planned_payments",
            id=uid("planned", p["id"]),
            clinic_id=clinic,
            date=p["date"],
            name=p["name"],
            amount=p["amount"],
            max_deferral_days=p["max_deferral_days"],
        )
    for c in data["counterparties"]:
        insert(
            "counterparties",
            conflict="(clinic_id, key)",
            clinic_id=clinic,
            key=c["inn"],
            name=c["name"],
            max_deferral_days=c["max_deferral_days"],
        )
    lines.extend(
        [
            "insert into public.memberships (clinic_id, user_id) "
            f"select {q(clinic)}, u.id from auth.users u where u.email = {q(EMAIL)} "
            "on conflict (user_id, clinic_id) do nothing;",
            "commit;",
        ]
    )
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    OUT.write_text(generate(json.loads(DATA.read_text(encoding="utf-8"))), encoding="utf-8")
    print(f"wrote {OUT}")

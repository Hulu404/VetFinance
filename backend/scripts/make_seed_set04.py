"""Generate the idempotent, transactional seed of report clinic E from golden set 4.

Requires all migrations through stage 3. Apply only to a test database. The synthetic
user test-e@vetfinance.test must already exist to link the clinic to a login.
No shared industry benchmark or existing clinic is modified.
"""

import json
import uuid
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "tests/golden/set04/data.json"
OUT = ROOT / "supabase/seed_set04.sql"
NS = uuid.UUID("ab59ba27-e621-4071-8e84-d3782ab0714e")
EMAIL = "test-e@vetfinance.test"


def uid(kind: str, key: str) -> str:
    return str(uuid.uuid5(NS, f"{kind}:{key}"))


def q(value: object) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def generate(data: dict[str, Any]) -> str:
    clinic = uid("clinic", "E")
    lines = [
        "-- GENERATED by backend/scripts/make_seed_set04.py from tests/golden/set04/data.json",
        "-- Synthetic clinic E. Requires migration 20261014100000_stage3_reports.",
        "-- Existing rows are preserved. Industry benchmarks come from the migration.",
        "begin;",
    ]

    def insert(table: str, **values: object) -> None:
        lines.append(
            f"insert into public.{table} ({', '.join(values)}) values "
            f"({', '.join(q(v) for v in values.values())}) on conflict (id) do nothing;"
        )

    insert(
        "clinics",
        id=clinic,
        name=data["clinic"]["name"],
        timezone=data["clinic"]["timezone"],
        acquiring_rate_bp=data["clinic"]["acquiring_rate_bp"],
    )
    for a in data["accounts"]:
        insert(
            "accounts",
            id=uid("account", a["id"]),
            clinic_id=clinic,
            name=a["name"],
            kind=a["type"],
            opening_balance=a["opening_balance"],
            opening_date=a["opening_date"],
            last_statement_to=data["bank_covered_to"] if a["type"] == "bank" else None,
        )
    for c in data["categories"]:
        insert("categories", id=uid("category", c["name"]), clinic_id=clinic, **c)
    for t in data["transactions"]:
        insert(
            "transactions",
            id=uid("tx", t["id"]),
            clinic_id=clinic,
            account_id=uid("account", t["account_id"]),
            date=t["date"],
            description=t["description"],
            amount=t["amount"],
            kind=t["kind"],
            source=t["source"],
            external_id=t["id"],
            status=t["status"],
            category_id=uid("category", t["category"]) if t["category"] else None,
        )
    for d in data["doctors"]:
        insert(
            "doctors",
            id=uid("doctor", d["id"]),
            clinic_id=clinic,
            external_id=d["id"],
            code=d["id"],
            name=d["name"],
        )
    for s in data["sales"]:
        insert(
            "sales",
            id=uid("sale", s["id"]),
            clinic_id=clinic,
            external_id=s["id"],
            date=s["date"],
            status=s["status"],
            amount=s["amount"],
            lines=json.dumps(s["lines"], ensure_ascii=False),
        )
    for p in data["payments"]:
        insert(
            "payments",
            id=uid("payment", p["id"]),
            clinic_id=clinic,
            external_id=p["id"],
            date=p["date"],
            amount=p["amount"],
            method=p["method"],
            invoice_external_id=p["invoice_id"],
        )
    kinds = {"loan_interest": "loan", "lease": "lease", "amortization": "equipment"}
    obligations = {c["obligation_id"]: c for c in data["obligation_charges"]}
    for code, c in obligations.items():
        insert(
            "obligations",
            id=uid("obligation", code),
            clinic_id=clinic,
            code=code,
            name=c["name"],
            kind=kinds[c["kind"]],
        )
    for c in data["obligation_charges"]:
        key = f"{c['obligation_id']}:{c['month']}:{c['kind']}"
        insert(
            "obligation_charges",
            id=uid("charge", key),
            clinic_id=clinic,
            obligation_id=uid("obligation", c["obligation_id"]),
            month=c["month"] + "-01",
            kind=c["kind"],
            amount=c["amount"],
            basis=c["basis"],
        )
    stock = data["stock"]
    for i in stock["items"]:
        insert(
            "stock_items",
            id=uid("item", i["id"]),
            clinic_id=clinic,
            external_id=i["id"],
            name=i["name"],
            last_movement_on=i["last_movement"],
        )
    for index, b in enumerate(stock["batches"]):
        key = f"S4-batch-{index:03d}"
        insert(
            "stock_batches",
            id=uid("batch", key),
            clinic_id=clinic,
            external_id=key,
            item_id=uid("item", b["item_id"]),
            qty=b["qty"],
            unit_cost=b["unit_cost"],
            expires_on=b["expires_on"],
        )
    item_ids = {i["name"]: uid("item", i["id"]) for i in stock["items"]}
    for w in stock["writeoffs"]:
        insert(
            "stock_writeoffs",
            id=uid("writeoff", w["id"]),
            clinic_id=clinic,
            external_id=w["id"],
            date=w["date"],
            item_id=item_ids.get(w["item"]),
            item_name=w["item"],
            qty=w["qty"],
            amount=w["amount"],
            reason=w["reason"],
        )
    for c in stock["consumption"]:
        insert(
            "stock_consumption",
            id=uid("consumption", c["date"]),
            clinic_id=clinic,
            date=c["date"],
            kind="total",
            amount=c["amount"],
        )
    lines.extend(
        [
            "insert into public.memberships (clinic_id, user_id) "
            f"select {q(clinic)}, u.id from auth.users u where u.email = {q(EMAIL)} "
            "on conflict (user_id, clinic_id) do nothing;",
            "commit;",
        ]
    )
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    OUT.write_text(generate(json.loads(DATA.read_text(encoding="utf-8"))), encoding="utf-8")
    print(f"wrote {OUT}")

"""Generate supabase/seed_set02.sql from tests/golden/set02/initial.json: the clean clinic C of golden set 2.

Run from the repository root:  backend/.venv/Scripts/python backend/scripts/make_seed_set02.py
The user test-c@vetfinance.test must exist in auth.users before the seed is applied (the membership is
linked by e-mail); otherwise the membership is simply skipped. The clinic starts without operations:
the end-to-end tests upload the statements and the Vetmanager export themselves. The seed is idempotent.
Apply it only to a throw-away or test clinic, never together with set 1 data of the same clinic.
"""

import json
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
INITIAL = ROOT / "tests" / "golden" / "set02" / "initial.json"
OUT = ROOT / "supabase" / "seed_set02.sql"
NS = uuid.UUID("6f1d8e0a-4b1c-4c8e-9a53-0d2f6c1b7e12")
EMAIL = "test-c@vetfinance.test"
# initial.json only says "expense"; the database distinguishes variable and fixed costs
FIXED = {"Аренда", "Коммунальные услуги", "Налоги и взносы", "Зарплата", "Прочие расходы"}


def uid(kind: str, key: str) -> str:
    return str(uuid.uuid5(NS, f"{kind}:{key}"))


def q(value: object) -> str:
    if value is None:
        return "null"
    if isinstance(value, int):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def category_type(category: dict[str, str]) -> str:
    if category["type"] == "income":
        return "income"
    return "fixed" if category["name"] in FIXED else "variable"


def main() -> None:
    data = json.loads(INITIAL.read_text(encoding="utf-8"))
    clinic = uid("clinic", "C")
    lines = [
        "-- GENERATED by backend/scripts/make_seed_set02.py from tests/golden/set02/initial.json",
        "-- Clean clinic C for the end-to-end tests of stage 1 (no operations).",
        "",
        "insert into public.clinics (id, name, timezone, safe_balance) values "
        f"({q(clinic)}, {q(data['clinic']['name'])}, {q(data['clinic']['timezone'])}, 0) "
        "on conflict (id) do nothing;",
    ]
    for account in data["accounts"]:
        lines.append(
            "insert into public.accounts (id, clinic_id, name, kind, number, opening_balance, opening_date) "
            f"values ({q(uid('account', account['key']))}, {q(clinic)}, {q(account['name'])}, "
            f"{q(account['kind'])}, {q(account['number'])}, {account['opening_balance']}, "
            f"{q(account['opening_date'])}) on conflict (id) do nothing;"
        )
    ids = {}
    for category in data["categories"]:
        ids[category["name"]] = uid("category", category["name"])
        lines.append(
            "insert into public.categories (id, clinic_id, name, type) values "
            f"({q(ids[category['name']])}, {q(clinic)}, {q(category['name'])}, {q(category_type(category))}) "
            "on conflict (id) do nothing;"
        )
    for rule in data["starter_rules"]:
        lines.append(
            "insert into public.category_rules (clinic_id, match, value, direction, category_id) values "
            f"({q(clinic)}, {q(rule['match'])}, {q(rule['value'])}, {q(rule['direction'])}, "
            f"{q(ids[rule['category']])}) on conflict do nothing;"
        )
    lines.append(
        "insert into public.memberships (clinic_id, user_id) "
        f"select {q(clinic)}, u.id from auth.users u where u.email = {q(EMAIL)} "
        "on conflict (user_id, clinic_id) do nothing;"
    )
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(lines)} lines)")


if __name__ == "__main__":
    main()

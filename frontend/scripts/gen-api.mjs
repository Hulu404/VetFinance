// Generates src/api/schema.gen.ts from ../backend/openapi.json.
// The export of the backend leaves nested `$defs` inside request bodies (RecipeBody, EfficiencySettingsBody),
// and their `#/$defs/...` references do not resolve from the document root. They are moved to components.schemas here
// (a copy in memory: the contract file is not touched). Asked of the backend in docs/handoff.md; the step is harmless when it is fixed.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const spec = JSON.parse(readFileSync(resolve(root, '../backend/openapi.json'), 'utf8'))
const schemas = (spec.components ??= {}).schemas ??= {}

function hoist(node) {
  if (Array.isArray(node)) return node.forEach(hoist)
  if (node === null || typeof node !== 'object') return
  if (node.$defs) {
    for (const [name, def] of Object.entries(node.$defs)) schemas[name] ??= def
    delete node.$defs
  }
  for (const value of Object.values(node)) hoist(value)
}
function rewrite(node) {
  if (Array.isArray(node)) return node.forEach(rewrite)
  if (node === null || typeof node !== 'object') return
  if (typeof node.$ref === 'string' && node.$ref.startsWith('#/$defs/')) node.$ref = node.$ref.replace('#/$defs/', '#/components/schemas/')
  for (const value of Object.values(node)) rewrite(value)
}
hoist(spec.paths)
rewrite(spec)
const ast = await openapiTS(spec)
const header = ['/**', ' * This file was auto-generated by openapi-typescript.', ' * Do not make direct changes to the file.', ' */', '', ''].join('\n')
writeFileSync(resolve(root, 'src/api/schema.gen.ts'), header + astToString(ast))
process.stdout.write('../backend/openapi.json -> src/api/schema.gen.ts\n')
